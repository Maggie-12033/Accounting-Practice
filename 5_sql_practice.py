# SQL 练习：建数据库 + 装假数据

import sqlite3
import pandas as pd

# ---------- 1. 连接数据库（文件不存在会自动创建）----------
conn = sqlite3.connect("practice.db")
cursor = conn.cursor()

# ---------- 2. 建表（如果已存在就先删掉，保证每次跑都是干净的）----------
cursor.execute("DROP TABLE IF EXISTS vouchers")

cursor.execute("""
CREATE TABLE vouchers (
    凭证号 TEXT,
    日期 TEXT,
    科目代码 TEXT,
    科目名称 TEXT,
    摘要 TEXT,
    借方 REAL,
    贷方 REAL
)
""")

# ---------- 3. 插入假数据 ----------
data = [
    ("记-001", "2026-09-01", "1001", "库存现金",   "提现",   5000,   0),
    ("记-001", "2026-09-01", "1002", "银行存款",   "提现",   0,      5000),
    ("记-002", "2026-09-05", "1122", "应收账款",   "销售",   30000,  0),
    ("记-002", "2026-09-05", "6001", "主营业务收入", "销售",  0,      30000),
    ("记-003", "2026-09-10", "1002", "银行存款",   "收款",   20000,  0),
    ("记-003", "2026-09-10", "1122", "应收账款",   "收款",   0,      20000),
    ("记-004", "2026-09-15", "6602", "管理费用",   "办公费", 3000,   0),
    ("记-004", "2026-09-15", "1002", "银行存款",   "办公费", 0,      3000),
    ("记-005", "2026-09-20", "1405", "库存商品",   "采购",   50000,  0),
    ("记-005", "2026-09-20", "2202", "应付账款",   "采购",   0,      50000),
]

cursor.executemany("INSERT INTO vouchers VALUES (?, ?, ?, ?, ?, ?, ?)", data)

conn.commit()

# ---------- 4. 验证：查全部 ----------
print("=== 全部凭证 ===")
df = pd.read_sql("SELECT * FROM vouchers", conn)
print(df)

conn.close()
print("\n数据库 practice.db 已建好，共", len(data), "行")